import assert from "node:assert/strict";
import { mkdir, readFile } from "node:fs/promises";
import { build } from "../vir/node_modules/esbuild/lib/main.js";

await mkdir(new URL("../player_js/generated/", import.meta.url), { recursive: true });
for (const name of ["animate_vir_widget", "diagram_widget"]) {
    await build({
        entryPoints: [new URL(`../player_js/${name}.js`, import.meta.url).pathname],
        outfile: new URL(`../player_js/generated/${name}.js`, import.meta.url).pathname,
        bundle: true,
        format: "esm",
        platform: "browser",
        target: "es2022",
        external: ["react", "@leanprover/infoview"],
        banner: { js: "// Generated by scripts/build-vir-widget.mjs." },
    });
}

const animateBundle = await readFile(
    new URL("../player_js/generated/animate_vir_widget.js", import.meta.url),
    "utf8",
);
assert.match(animateBundle, /Illuminate\.Animation\.Vir\.mountSelectionPlayer/);
assert.match(animateBundle, /data-illuminate-player-boundary/);
assert.doesNotMatch(animateBundle, /Illuminate\.Animation\.Vir\.mountInfoView/);

await build({
    entryPoints: [new URL("../player_js/hit_scene_performance.js", import.meta.url).pathname],
    outfile: new URL("../player_js/generated/hit_scene_performance.js", import.meta.url).pathname,
    bundle: true,
    format: "esm",
    platform: "browser",
    target: "es2022",
    external: ["node:fs/promises"],
    banner: { js: "// Generated by scripts/build-vir-widget.mjs." },
});
